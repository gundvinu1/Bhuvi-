import { ChunkingService } from './chunking.service';

describe('ChunkingService', () => {
  let service: ChunkingService;

  beforeEach(() => {
    service = new ChunkingService();
  });

  it('should return empty array for empty or whitespace-only text', () => {
    expect(service.chunkText('')).toEqual([]);
    expect(service.chunkText('   \n\t  ')).toEqual([]);
    expect(service.chunkText(null as any)).toEqual([]);
  });

  it('should return a single chunk if text fits within chunkSize', () => {
    const text = 'This is a short personal memory note about my favorite books.';
    const chunks = service.chunkText(text, { chunkSize: 500 });

    expect(chunks).toHaveLength(1);
    expect(chunks[0]!.chunkIndex).toBe(0);
    expect(chunks[0]!.content).toBe(text);
    expect(chunks[0]!.tokenCount).toBeGreaterThan(0);
  });

  it('should split long multi-paragraph text into overlapping chunks', () => {
    const p1 =
      'BHUVI is a personal AI operating system designed for high privacy and local-first execution.';
    const p2 =
      'It supports long-term memory using vector embeddings generated by local Ollama models.';
    const p3 =
      'Users can organize memories into 8 categories including PERSONAL, WORK, PROJECT, and EDUCATION.';
    const p4 =
      'Semantic search allows fast cosine similarity retrieval over PostgreSQL stored vector chunks.';
    const fullText = `${p1}\n\n${p2}\n\n${p3}\n\n${p4}`;

    const chunks = service.chunkText(fullText, { chunkSize: 120, chunkOverlap: 30 });

    expect(chunks.length).toBeGreaterThan(1);
    expect(chunks[0]!.chunkIndex).toBe(0);
    expect(chunks[1]!.chunkIndex).toBe(1);

    // Verify indices are sequential
    for (let i = 0; i < chunks.length; i++) {
      expect(chunks[i]!.chunkIndex).toBe(i);
      expect(chunks[i]!.tokenCount).toBeGreaterThan(0);
    }
  });

  it('should split very long sentences cleanly without exceeding chunkSize', () => {
    const longSentence =
      'Artificial intelligence systems operating locally provide privacy guarantees that cloud-based solutions cannot match because all personal data stays strictly on user hardware without transmitting confidential tokens to external servers.';

    const chunks = service.chunkText(longSentence, { chunkSize: 80, chunkOverlap: 20 });
    expect(chunks.length).toBeGreaterThan(1);
  });

  it('should estimate token counts based on word frequency', () => {
    const text = 'One two three four five six seven eight nine ten.';
    const tokens = service.estimateTokens(text);
    expect(tokens).toBe(13); // 10 * 1.3 = 13
    expect(service.estimateTokens('')).toBe(0);
  });
});
